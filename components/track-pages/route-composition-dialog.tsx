"use client";

import { ArrowDown, ArrowUp, Plus, Trash2 } from "lucide-react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { useEffect, useMemo, useRef, useState } from "react";
import { toast } from "sonner";

import { createCompositeRoute, replaceRouteComposition } from "@/app/_data/route-compositions";
import { getRouteCompositionSegments, type RouteListItem } from "@/app/_data/routes";
import {
  Badge,
  Button,
  ConfirmDialog,
  Dialog,
  DialogContent,
  DialogFooter,
  DialogHeader,
  DialogTitle,
  Input,
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
  Spinner,
} from "@/components/index";
import { ROUTE_TITLE_MAX_LENGTH } from "@/lib/route-title";

// feature-153: the route builder. A composite route is a recipe, so the dialog
// collects an ordered list of existing routes and a lap count per segment — no
// map, no placed points. The geometry is generated by the server and previewed
// through the ordinary preview dialog afterwards.
//
// The copy is English like the rest of the route library; localization is a
// separate candidate.

type SegmentRow = {
  key: string;
  childRouteId: string;
  /** Kept as the input's own string so a cleared field is not read as zero. */
  lapCount: string;
};

type RouteCompositionDialogProps = {
  /** `null` creates a composite route; a stored row edits its recipe. */
  route: RouteListItem | null;
  /** Every route the owner has; eligible children are derived from it. */
  routes: RouteListItem[];
  open: boolean;
  onOpenChange: (open: boolean) => void;
  /** The owner has no routes at all — offer the point-based creation path. */
  onCreatePlainRoute?: () => void;
};

const formatCount = (count: number, noun: string) => `${count} ${noun}${count === 1 ? "" : "s"}`;

export const RouteCompositionDialog = ({
  route,
  routes,
  open,
  onOpenChange,
  onCreatePlainRoute,
}: RouteCompositionDialogProps) => {
  const router = useRouter();
  const isEdit = Boolean(route);
  const [title, setTitle] = useState(route?.title ?? "");
  const [description, setDescription] = useState(route?.description ?? "");
  const [segments, setSegments] = useState<SegmentRow[]>([]);
  const [isLoading, setIsLoading] = useState(isEdit);
  const [isSaving, setIsSaving] = useState(false);
  const [sharedConfirmOpen, setSharedConfirmOpen] = useState(false);
  const [sharedTrackCount, setSharedTrackCount] = useState(0);
  const keyCounter = useRef(0);

  const nextKey = () => {
    keyCounter.current += 1;

    return `segment-${keyCounter.current}`;
  };

  // Only a plain route can be a segment: the server refuses a nested
  // composition, and the edited parent cannot use itself.
  const eligibleRoutes = useMemo(
    () => routes.filter((candidate) => !candidate.isComposite && candidate.id !== route?.id),
    [route?.id, routes],
  );

  useEffect(() => {
    if (!open || !isEdit || !route) return;

    let cancelled = false;
    setIsLoading(true);

    getRouteCompositionSegments(route.id)
      .then((detail) => {
        if (cancelled) return;

        if (!detail) {
          toast.error("This route has no composition to edit");
          onOpenChange(false);

          return;
        }

        setTitle(detail.title);
        setDescription(detail.description ?? "");
        setSegments(
          detail.segments.map((segment) => ({
            key: nextKey(),
            childRouteId: segment.childRouteId,
            lapCount: String(segment.lapCount),
          })),
        );
      })
      .catch((error) => {
        if (cancelled) return;
        toast.error(error instanceof Error ? error.message : "Could not load the route composition");
        onOpenChange(false);
      })
      .finally(() => {
        if (!cancelled) setIsLoading(false);
      });

    return () => {
      cancelled = true;
    };
    // The dialog is remounted per open through `key`; the recipe is read once.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open, isEdit, route?.id]);

  const totalLaps = segments.reduce((total, segment) => total + (Number(segment.lapCount) || 0), 0);

  const updateSegment = (key: string, patch: Partial<SegmentRow>) => {
    setSegments((current) => current.map((segment) => (segment.key === key ? { ...segment, ...patch } : segment)));
  };

  const addSegment = () => {
    const fallback = eligibleRoutes[0]?.id ?? "";

    setSegments((current) => [...current, { key: nextKey(), childRouteId: fallback, lapCount: "1" }]);
  };

  const removeSegment = (key: string) => {
    setSegments((current) => current.filter((segment) => segment.key !== key));
  };

  const moveSegment = (index: number, direction: -1 | 1) => {
    const target = index + direction;

    if (target < 0 || target >= segments.length) return;

    setSegments((current) => {
      const next = [...current];
      const [moved] = next.splice(index, 1);
      next.splice(target, 0, moved);

      return next;
    });
  };

  const trimmedTitle = title.trim();
  const titleTooLong = trimmedTitle.length > ROUTE_TITLE_MAX_LENGTH;
  const everySegmentComplete = segments.every(
    (segment) => segment.childRouteId && Number.isInteger(Number(segment.lapCount)) && Number(segment.lapCount) >= 1,
  );
  const isMeaningful = segments.length > 1 || (segments.length === 1 && Number(segments[0].lapCount) > 1);
  const canSave =
    !isLoading &&
    !isSaving &&
    !titleTooLong &&
    Boolean(trimmedTitle) &&
    Boolean(description.trim().length <= 2000) &&
    everySegmentComplete &&
    isMeaningful;

  const submit = async (confirmShared: boolean) => {
    const payload = segments.map((segment, index) => ({
      childRouteId: segment.childRouteId,
      role: "MAIN",
      sortOrder: index,
      lapCount: Number(segment.lapCount),
    }));

    setIsSaving(true);

    try {
      if (route) {
        const result = await replaceRouteComposition({
          routeId: route.id,
          segments: payload,
          confirmShared,
        });

        if (!result.ok) {
          if (result.code === "SHARED_CONFIRMATION") {
            setSharedTrackCount("linkedTrackCount" in result ? (result.linkedTrackCount ?? 0) : 0);
            setSharedConfirmOpen(true);

            return;
          }

          toast.error(result.message);

          return;
        }

        toast.success("Route composition updated");
        router.refresh();
        onOpenChange(false);

        return;
      }

      const result = await createCompositeRoute({
        title: trimmedTitle,
        description: description.trim() || null,
        segments: payload,
      });

      if (!result.ok) {
        toast.error(result.message);

        return;
      }

      toast.success("Composite route created");
      router.refresh();
      onOpenChange(false);
    } catch (error) {
      toast.error(error instanceof Error ? error.message : "Could not save the route composition");
    } finally {
      setIsSaving(false);
    }
  };

  const handleSharedConfirm = async () => {
    setSharedConfirmOpen(false);
    await submit(true);
  };

  const renderEmptyState = () => {
    if (routes.length === 0) {
      return (
        <div className="grid gap-2 rounded-md border border-dashed p-4 text-sm">
          <p className="font-medium">You have no routes yet</p>
          <p className="text-muted-foreground">
            A composite route is built from routes you already have. Create a route with placed points first.
          </p>
          {onCreatePlainRoute ? (
            <Button type="button" variant="outline" className="w-fit" onClick={onCreatePlainRoute}>
              <Plus />
              New route
            </Button>
          ) : null}
        </div>
      );
    }

    return (
      <div className="grid gap-2 rounded-md border border-dashed p-4 text-sm">
        <p className="font-medium">No route can be used as a segment</p>
        <p className="text-muted-foreground">
          Every route you have is already a composition. A composition cannot contain another composition.
        </p>
        <Link href="/my/routes" className="w-fit font-medium underline underline-offset-4">
          Back to My routes
        </Link>
      </div>
    );
  };

  return (
    <>
      <Dialog open={open} onOpenChange={(nextOpen) => !isSaving && onOpenChange(nextOpen)}>
        <DialogContent
          className="max-h-[calc(100dvh-2rem)] overflow-y-auto sm:max-w-2xl"
          aria-describedby="route-composition-description"
        >
          <DialogHeader>
            <DialogTitle>{isEdit ? "Edit composite route" : "New composite route"}</DialogTitle>
          </DialogHeader>
          <p id="route-composition-description" className="sr-only">
            {isEdit
              ? "Change the title, the description, the order of the segments, or the lap counts. Saving regenerates the route's shape."
              : "Build a route from existing routes. Choose the order and the lap count of each segment."}
          </p>

          {isLoading ? (
            <div className="flex justify-center py-10">
              <Spinner className="size-6" />
            </div>
          ) : (
            <div className="grid gap-4">
              <div className="grid gap-2">
                <label htmlFor="route-composition-title" className="text-sm font-medium">
                  Title
                </label>
                <Input
                  id="route-composition-title"
                  value={title}
                  maxLength={200}
                  disabled={isSaving}
                  placeholder="Three park laps"
                  onChange={(event) => setTitle(event.target.value)}
                />
                {titleTooLong ? (
                  <p className="text-destructive text-sm">Title must be {ROUTE_TITLE_MAX_LENGTH} characters or fewer</p>
                ) : null}
              </div>

              <div className="grid gap-2">
                <label htmlFor="route-composition-description-field" className="text-sm font-medium">
                  Description
                </label>
                <textarea
                  id="route-composition-description-field"
                  value={description}
                  maxLength={2000}
                  disabled={isSaving}
                  className="border-input focus-visible:border-ring focus-visible:ring-ring/50 min-h-20 w-full rounded-md border bg-transparent px-3 py-2 text-sm shadow-xs outline-none focus-visible:ring-[3px]"
                  placeholder="What this route is for, and where it goes."
                  onChange={(event) => setDescription(event.target.value)}
                />
              </div>

              {eligibleRoutes.length === 0 ? (
                renderEmptyState()
              ) : (
                <div className="grid gap-3">
                  <div className="flex items-center justify-between gap-2">
                    <span className="text-sm font-medium">Segments</span>
                    {segments.length > 0 ? (
                      <Badge variant="secondary">
                        {formatCount(segments.length, "segment")} · {formatCount(totalLaps, "lap")}
                      </Badge>
                    ) : null}
                  </div>

                  {segments.length === 0 ? (
                    <p className="text-muted-foreground text-sm">
                      Add at least two segments, or one segment repeated more than once.
                    </p>
                  ) : null}

                  <div className="grid gap-2">
                    {segments.map((segment, index) => (
                      <div key={segment.key} className="flex flex-wrap items-center gap-2 rounded-md border p-2">
                        <span className="text-muted-foreground w-6 text-sm">{index + 1}.</span>
                        <Select
                          value={segment.childRouteId}
                          disabled={isSaving}
                          onValueChange={(value) => updateSegment(segment.key, { childRouteId: value })}
                        >
                          <SelectTrigger className="min-w-40 flex-1">
                            <SelectValue placeholder="Choose a route" />
                          </SelectTrigger>
                          <SelectContent>
                            {eligibleRoutes.map((candidate) => (
                              <SelectItem key={candidate.id} value={candidate.id}>
                                {candidate.title}
                              </SelectItem>
                            ))}
                          </SelectContent>
                        </Select>

                        <div className="flex items-center gap-1">
                          <label htmlFor={`lap-count-${segment.key}`} className="text-muted-foreground text-sm">
                            Laps
                          </label>
                          <Input
                            id={`lap-count-${segment.key}`}
                            type="number"
                            min="1"
                            step="1"
                            inputMode="numeric"
                            className="w-20"
                            value={segment.lapCount}
                            disabled={isSaving}
                            onChange={(event) => updateSegment(segment.key, { lapCount: event.target.value })}
                          />
                        </div>

                        <div className="flex items-center gap-1">
                          <Button
                            type="button"
                            variant="ghost"
                            size="icon"
                            title="Move up"
                            aria-label="Move segment up"
                            disabled={isSaving || index === 0}
                            onClick={() => moveSegment(index, -1)}
                          >
                            <ArrowUp className="size-4" />
                          </Button>
                          <Button
                            type="button"
                            variant="ghost"
                            size="icon"
                            title="Move down"
                            aria-label="Move segment down"
                            disabled={isSaving || index === segments.length - 1}
                            onClick={() => moveSegment(index, 1)}
                          >
                            <ArrowDown className="size-4" />
                          </Button>
                          <Button
                            type="button"
                            variant="ghost"
                            size="icon"
                            title="Remove segment"
                            aria-label="Remove segment"
                            disabled={isSaving}
                            onClick={() => removeSegment(segment.key)}
                          >
                            <Trash2 className="size-4" />
                          </Button>
                        </div>
                      </div>
                    ))}
                  </div>

                  <Button type="button" variant="outline" className="w-fit" disabled={isSaving} onClick={addSegment}>
                    <Plus />
                    Add segment
                  </Button>

                  {segments.length === 1 && Number(segments[0].lapCount) <= 1 ? (
                    <p className="text-destructive text-sm">
                      One segment with one lap would only copy that route. Add another segment or raise the lap count.
                    </p>
                  ) : null}
                </div>
              )}
            </div>
          )}

          <DialogFooter>
            <Button type="button" variant="outline" disabled={isSaving} onClick={() => onOpenChange(false)}>
              Cancel
            </Button>
            <Button type="button" disabled={!canSave} onClick={() => void submit(false)}>
              {isSaving ? <Spinner className="size-6" /> : isEdit ? "Save route" : "Create route"}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>

      <ConfirmDialog
        open={sharedConfirmOpen}
        onOpenChange={setSharedConfirmOpen}
        title="Replace the shared route?"
        description={`This route is used by ${formatCount(sharedTrackCount, "track")}. The new shape will replace it everywhere.`}
        confirmLabel="Replace everywhere"
        confirmVariant="destructive"
        isPending={isSaving}
        onConfirm={handleSharedConfirm}
      />
    </>
  );
};
